// Build an SVG sprite containing only the Lucide icons the templates actually use.
// Usage in templates: {% icon "search" "h-4 w-4" %}. Extra (dynamic) names live in icons.extra.json.
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const APPS = ["venues", "accounts", "tracker", "community", "config"];
const ICON_RE = /\{%\s*icon\s+["']([a-z0-9-]+)["']/g;

function walk(dir, acc = []) {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) walk(p, acc);
    else if (/\.(html|py|js)$/.test(name)) acc.push(p);
  }
  return acc;
}

const names = new Set(JSON.parse(readFileSync(join(root, "frontend/icons.extra.json"), "utf8")));
for (const app of APPS) {
  for (const file of walk(join(root, app))) {
    for (const m of readFileSync(file, "utf8").matchAll(ICON_RE)) names.add(m[1]);
  }
}

const iconsDir = join(root, "node_modules/lucide-static/icons");
const version = JSON.parse(readFileSync(join(root, "node_modules/lucide-static/package.json"), "utf8")).version;
const symbols = [];
const missing = [];
for (const name of [...names].sort()) {
  let svg;
  try {
    svg = readFileSync(join(iconsDir, `${name}.svg`), "utf8");
  } catch {
    missing.push(name);
    continue;
  }
  const inner = svg.slice(svg.indexOf(">", svg.indexOf("<svg")) + 1, svg.lastIndexOf("</svg>"))
    .replace(/\s*\n\s*/g, "");
  symbols.push(`<symbol id="${name}" viewBox="0 0 24 24">${inner}</symbol>`);
}
if (missing.length) {
  console.error(`Unknown Lucide icon(s): ${missing.join(", ")}`);
  process.exit(1);
}
writeFileSync(
  join(root, "venues/static/venues/img/icons.svg"),
  `<svg xmlns="http://www.w3.org/2000/svg"><!-- Lucide v${version} (ISC) https://lucide.dev — generated by npm run build:icons -->${symbols.join("")}</svg>\n`,
);
console.log(`icon sprite: ${symbols.length} icons`);
