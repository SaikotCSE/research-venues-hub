// Copy runtime JavaScript dependencies from node_modules into Django's static tree so the
// site never depends on a third-party CDN at runtime. Run with `npm run vendor`.
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const out = join(root, "venues/static/venues/vendor");
mkdirSync(out, { recursive: true });

const files = [
  { pkg: "htmx.org", from: "dist/htmx.min.js", to: "htmx.min.js" },
  { pkg: "alpinejs", from: "dist/cdn.min.js", to: "alpine.min.js" },
  { pkg: "chart.js", from: "dist/chart.umd.js", to: "chart.umd.min.js" },
];

const rows = [];
for (const f of files) {
  const meta = JSON.parse(readFileSync(join(root, "node_modules", f.pkg, "package.json"), "utf8"));
  copyFileSync(join(root, "node_modules", f.pkg, f.from), join(out, f.to));
  rows.push(`| ${f.to} | ${f.pkg} | ${meta.version} | ${meta.license} | ${meta.homepage || ""} |`);
  console.log(`vendored ${f.pkg}@${meta.version} -> ${f.to}`);
}

writeFileSync(
  join(out, "LICENSES.md"),
  [
    "# Vendored third-party front-end libraries",
    "",
    "Generated by `npm run vendor` — do not edit by hand. Versions are pinned in package.json.",
    "",
    "| File | Package | Version | License | Homepage |",
    "|------|---------|---------|---------|----------|",
    ...rows,
    "",
    "Icons in `../img/icons.svg` come from lucide-static (ISC license, https://lucide.dev).",
    "",
  ].join("\n"),
);
